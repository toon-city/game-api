-- V28: rescale the 4 public rooms' geometry + decor from V27.
--
-- V27 carried the old game's STRUCT/placement coordinates through with NO
-- extra scale factor beyond the point/wall/door transform itself (only
-- validated, at the time, against a private-apartment shape with zero
-- furniture placed in it — nothing to catch a missing uniform scale
-- against). Visually confirmed live once these 4 public rooms actually had
-- real furniture in them: rooms came out enormous (Quizz alone rendered
-- ~1920x500 screen-px, Jardin ~5360x1640) and furniture read as tiny,
-- sparse dots scattered across an empty floor.
--
-- Considered instead making the furniture SPRITES themselves bigger (bigger
-- exported PNGs / a bigger declared spritesheet "scale") while leaving
-- room+placement coordinates at V27's un-scaled values — tried this live
-- (halved the furniture spritesheets' declared "scale" values) and it
-- overshot badly: a piece's on-screen size and its distance to its
-- neighbours are independent quantities, so enlarging the sprite while
-- leaving placement spacing untouched didn't fix "sparse", it just made
-- each already-correctly-avatar-proportioned piece render 3x too big next
-- to the avatar (confirmed live: a single Jardin statue filled the entire
-- viewport). The furniture sprites were never wrong at their native size —
-- only the SPACING between placements (inherited straight from the old
-- game's own much larger world) was too sprawling. Reverted that asset
-- change entirely (see game-assets' own history) in favour of this: scale
-- room points, wall door offsets and every placed piece's x/y uniformly,
-- leaving the furniture spritesheets and wall height (h) untouched.
--
-- Scale factor 0.333, chosen to bring the largest room (Jardin) down to
-- roughly the same order of magnitude as this engine's other rooms while
-- keeping all 4 rooms' relative proportions to each other (a public room is
-- still meant to be bigger than a private house). Scaling commutes through
-- the linear rotate+isometric-project pipeline, so scaling house_data's
-- final point x/y and each door's offset (both in the same final projected-
-- space unit system) is equivalent to scaling the original pre-projection
-- STRUCT coordinates by the same factor; same reasoning for every placed
-- piece's already-projected x/y. Wall height (h) is left unscaled on
-- purpose — an established, separately-validated convention (every other
-- room in this engine uses h:250/h:10 regardless of floor-plan size).
--
-- Verified live: avatar-to-furniture proportions read correctly in all 4
-- rooms (Quizz's camera towers/buzzer podium, Jardin's statues/hedges/
-- fountain, Discotchat's bar/dancefloor, Maison hantée's candelabras/divans
-- all sit at a believable scale next to the avatar instead of looking like
-- tiny props scattered across an oversized floor).

